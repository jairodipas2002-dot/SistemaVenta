public void validar() {
    String correo = txtcorreo.getText().trim();
    String pass = String.valueOf(txtpass.getPassword());
    if (pass.length() < 8) {
    JOptionPane.showMessageDialog(this,
            "La contraseña debe tener como mínimo 8 caracteres");
    txtpass.requestFocus();
    return;
}

if (!pass.matches(".*[a-z].*")) {
    JOptionPane.showMessageDialog(this,
            "La contraseña debe contener al menos una letra minúscula");
    txtpass.requestFocus();
    return;
}

if (!pass.matches(".*[A-Z].*")) {
    JOptionPane.showMessageDialog(this,
            "La contraseña debe contener al menos una letra mayúscula");
    txtpass.requestFocus();
    return;
}

if (!pass.matches(".*\\d.*")) {
    JOptionPane.showMessageDialog(this,
            "La contraseña debe contener al menos un número");
    txtpass.requestFocus();
    return;
}

if (!pass.matches(".*[^a-zA-Z0-9].*")) {
    JOptionPane.showMessageDialog(this,
            "La contraseña debe contener al menos un símbolo especial");
    txtpass.requestFocus();
    return;
}
    String nom = txtNombre.getText().trim();
    String rol = cbxRol.getSelectedItem().toString();

    // Verificar que todos los campos estén todos llenos
    if (correo.isEmpty() || pass.isEmpty() || nom.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Complete todos los campos");
        return;
    }

    lg.setNombre(nom);
    lg.setCorreo(correo);
    lg.setPass(pass); 
    lg.setRol(rol);

    // Registrar el usuario en la base de datos
    boolean registrado = login.Registrar(lg);

    if (registrado) {
        JOptionPane.showMessageDialog(this,
                "Usuario registrado correctamente");

        Login iniciar = new Login();
        iniciar.setVisible(true);
        dispose();
    } else {
        JOptionPane.showMessageDialog(this,
                "No se pudo registrar el usuario. Revise la consola.");
    }
}

